import assert from 'node:assert/strict';
import { EventEmitter } from 'node:events';
import { PassThrough } from 'node:stream';
import fs from 'node:fs';
import { setTimeout as delay } from 'node:timers/promises';
import { observeSourceTiming, createSourceTimingFile } from '../source-timing.mjs';

const process = () => Object.assign(new EventEmitter(),{stdout:new PassThrough(),stderr:new PassThrough()});
const ytdlp = process(), ffmpeg = process();
const destination = new PassThrough();
const audio = [];
destination.on('data', chunk => audio.push(chunk));
ytdlp.stdout.pipe(destination);
let now = 1000;
const logs=[];
const diagnosticFile=createSourceTimingFile();
assert.ok(fs.statSync(diagnosticFile.path).isFile());
assert.deepEqual(diagnosticFile.args,['--no-simulate','--print-to-file','before_dl:M1S_TIMING_BEFORE_DOWNLOAD!',diagnosticFile.path]);
assert.ok(!diagnosticFile.args.includes('/dev/stderr'));
const observer=observeSourceTiming({ytdlp,ffmpeg,diagnosticFile,startedAt:1000,label:'[Test] session=1 track=2',now:()=>now,log:(_level,line)=>logs.push(line)});
now=1010;ytdlp.emit('spawn');now=1012;ffmpeg.emit('spawn');
now=2000;fs.writeFileSync(diagnosticFile.path,'M1S_TIMING_BEFORE_');
await delay(70);
assert.equal(logs.length,2,'partial marker must not be recorded');
fs.appendFileSync(diagnosticFile.path,'DOWNLOAD!\n');
for(let attempt=0;attempt<100 && logs.length<3;attempt++) await delay(10);
assert.equal(logs.length,3,'complete regular-file marker must be observed');
now=3000;ytdlp.stdout.write(Buffer.from([0,255,128,64]));
now=3500;observer.firstPcm();observer.firstPcm();
fs.appendFileSync(diagnosticFile.path,'M1S_TIMING_BEFORE_DOWNLOAD!\n');
now=4000;ytdlp.stdout.write(Buffer.from([3,2,1]));
ytdlp.emit('close',0,null);ffmpeg.emit('close',null,'SIGTERM');
assert.ok(!fs.existsSync(diagnosticFile.path),'temporary file is removed on close');
assert.deepEqual(Buffer.concat(audio),Buffer.from([0,255,128,64,3,2,1]),'diagnostics must preserve every audio byte');
assert.equal(logs.length,7);
assert.ok(logs.some(line=>line.includes('ytdlp_before_download_ms=1000')));
assert.ok(logs.some(line=>line.includes('download_to_first_byte_ms=1000')));
assert.ok(logs.some(line=>line.includes('pipe_to_pcm_ms=500')));
assert.ok(logs.some(line=>line.includes('signal=SIGTERM')));
const missing = process(), missingFfmpeg=process(), missingLogs=[];
const unknown=observeSourceTiming({ytdlp:missing,ffmpeg:missingFfmpeg,startedAt:1000,label:'test',now:()=>4000,log:(_level,line)=>missingLogs.push(line)});
unknown.firstPcm();
assert.ok(missingLogs[0].includes('pipe_to_pcm_ms=unknown'));
missing.stdout.write('audio');
assert.ok(missingLogs[1].includes('download_to_first_byte_ms=unknown'));
console.log('PASS: regular-file timing marker, polling/cleanup, one-time events, missing-stage handling and byte-identical audio.');
