import assert from 'node:assert/strict';
import fs from 'node:fs';
const app = fs.readFileSync(new URL('../node_modules/yt-cast-receiver/dist/lib/app/YouTubeApp.js', import.meta.url), 'utf8');
assert.match(app, /M1S 1\.0\.10 YTM sidecar state\/control bridge/);
const incomingStart = app.indexOf('_YouTubeApp_handleIncomingMessage = async function');
const incomingEnd = app.indexOf('}, _YouTubeApp_handleSenderConnected = async function', incomingStart);
assert.ok(incomingStart >= 0 && incomingEnd > incomingStart);
const incoming = app.slice(incomingStart, incomingEnd);
assert.match(incoming, /const m1sCanControl = isSessionActive \|\| m1sYtmSidecar/);
assert.equal((incoming.match(/if \(!m1sCanControl\) return;/g) || []).length, 9);
assert.doesNotMatch(incoming, /if \(!isSessionActive\)\s*return;/);
const stateStart = app.indexOf('_YouTubeApp_handlePlayerStateEvent = function');
const stateEnd = app.indexOf('\n};\nexport default YouTubeApp;', stateStart);
assert.ok(stateStart >= 0 && stateEnd > stateStart);
const state = app.slice(stateStart, stateEnd);
assert.equal((state.match(/m1sYtmStateSession\.sendMessage\(messages\)/g) || []).length, 2);
assert.equal((state.match(/_YouTubeApp_activeSession, "f"\)\.sendMessage\(messages/g) || []).length, 2);
const cfg = fs.readFileSync(new URL('../config.yaml', import.meta.url), 'utf8');
const pkg = JSON.parse(fs.readFileSync(new URL('../package.json', import.meta.url), 'utf8'));
assert.match(cfg, /version: "1\.0\.12"/);
assert.equal(pkg.version, '1.0.12');
console.log('PASS: installed 1.0.12 dependency contains nine YTM control guards and two state mirrors; active sends retained.');
